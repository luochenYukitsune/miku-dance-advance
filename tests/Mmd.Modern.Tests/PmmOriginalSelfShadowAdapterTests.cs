    private static PmmCameraPose ObservedCamera => new(new(7, 13, -4), new(.31f, -.47f, .22f), -37, 45, true);
    private static PmmLightPose ObservedLight => new(Vector3.One, new(-.35f, -.9f, .6f));

    [Fact]
    public void AsymmetricOrbitMatchesActualOriginalCapturedMatrix()
    {
        // Instrumented original host -> original builder -> final matrix, not generated by product.
        // shadow-orbit/asymmetric/report.json, ordinal 1; original EXE SHA 882c97dc...87156.
        var expected = new Matrix4x4(
            .018797283992171288f, .010243581607937813f, .002041382249444723f, .005121790803968906f,
            -.011032980866730213f, .00820123590528965f, .000714417896233499f, .004100617952644825f,
            -.005584389436990023f, .018277276307344437f, .005459913052618504f, .009138638153672218f,
            -.010489819571375847f, -.2749839425086975f, .30635368824005127f, 1.3625080585479736f);
        var actual = PmmOriginalSelfShadowAdapter.Create(ObservedCamera, ObservedLight,
            new(1, BitConverter.UInt32BitsToSingle(0x3c3851ec)), Matrix4x4.Identity)!;
        foreach (var point in new[] { Vector3.Zero, new Vector3(2, -5, 8), new Vector3(-3, 7, -2), new Vector3(23, 14, 6) })
            Near(Vector4.Transform(new Vector4(point, 1), expected), Vector4.Transform(new Vector4(point, 1), actual.LightViewProjection), 3e-6f);
        Assert.False(actual.PartialFar);
        var eyeShortcut = OriginalShadowTransform.Create(Matrix4x4.Identity, ObservedCamera.CreateCamera().Eye,
            ObservedLight.Direction, .01125f, 1);
        Assert.True(Vector4.Distance(Vector4.Transform(Vector4.UnitW, expected),
            Vector4.Transform(Vector4.UnitW, eyeShortcut.LightViewProjection)) > .1f);
    }

    [Theory]
    [InlineData(1)]
    [InlineData(2)]
    public void RawScaleAndDirectionAndNonidentityWorldAreAppliedOnce(int mode)
    {
        var camera = ObservedCamera;
        var world = Matrix4x4.CreateScale(1.3f, .8f, 1.1f) * Matrix4x4.CreateRotationY(.2f) * Matrix4x4.CreateTranslation(4, -3, 7);
        var actual = PmmOriginalSelfShadowAdapter.Create(camera, ObservedLight, new((byte)mode, .023f), world)!;
        var identity = PmmOriginalSelfShadowAdapter.Create(camera, ObservedLight, new((byte)mode, .023f), Matrix4x4.Identity)!;
        var normalized = PmmOriginalSelfShadowAdapter.Create(camera,
            ObservedLight with { Direction = Vector3.Normalize(ObservedLight.Direction) }, new((byte)mode, .023f), world)!;
        foreach (var point in new[] { new Vector3(1, 2, 3), new Vector3(-5, 3, 8) })
        {
            var clip = Vector4.Transform(new Vector4(point, 1), actual.LightViewProjection);
            Near(Vector4.Transform(Vector4.Transform(new Vector4(point, 1), world), identity.LightViewProjection), clip, 4e-6f);
            Assert.True(Vector4.Distance(clip, Vector4.Transform(new Vector4(point, 1), normalized.LightViewProjection)) > .001f);
        }
        var q = Matrix4x4.CreateRotationY(camera.Angle.Y) * Matrix4x4.CreateRotationX(camera.Angle.X) * Matrix4x4.CreateRotationZ(camera.Angle.Z);
        var direct = OriginalShadowTransform.Create(world * Matrix4x4.CreateTranslation(-camera.LookAt) * q,
            new(0, 0, camera.Distance), Vector3.TransformNormal(ObservedLight.Direction, q), .023f, mode);
        Assert.Equal(direct.LightViewProjection, actual.LightViewProjection);
        Assert.Equal(mode == 2, actual.PartialFar);
    }

    [Fact]
    public void MapPolicyIsExplicitAndTemplateSelectionsArePreserved()
    {
        var defaultMap = PmmOriginalSelfShadowAdapter.Create(ObservedCamera, ObservedLight, new(1, .01125f), Matrix4x4.Identity)!;
        Assert.Equal(2048, defaultMap.Width); Assert.Equal(2048, defaultMap.Height);
        Assert.Equal(OriginalTextureSampling.PointClamp, defaultMap.Sampling);
        Assert.Equal(OriginalDepthComparison.LessEqual, defaultMap.DepthComparison);
        var template = new OriginalSelfShadowOptions(Matrix4x4.Identity, 128, 64, false, true,
            OriginalTextureSampling.LinearClamp, OriginalDepthComparison.Less);
        var result = PmmOriginalSelfShadowAdapter.Create(ObservedCamera, ObservedLight, new(1, .01125f), Matrix4x4.Identity, template)!;
        Assert.Equal(128, result.Width); Assert.Equal(64, result.Height);
        Assert.Equal(template.Sampling, result.Sampling); Assert.Equal(template.DepthComparison, result.DepthComparison);
        Assert.True(result.Generate); Assert.False(result.PartialFar); Assert.False(template.Generate); Assert.True(template.PartialFar);
        Assert.Throws<ArgumentException>(() => PmmOriginalSelfShadowAdapter.Create(ObservedCamera, ObservedLight,
            new(1, .01125f), Matrix4x4.Identity, template with { Width = 0 }));
    }

    [Fact]
    public void DisabledModeNeedsNoProjectionAndUnsupportedInputsAreExplicit()
    {
        Assert.Null(PmmOriginalSelfShadowAdapter.Create(default, default, new(0, float.NaN), default));
        Assert.Throws<NotSupportedException>(() => PmmOriginalSelfShadowAdapter.Create(
            ObservedCamera with { ParentModelIndex = 0 }, ObservedLight, new(1, .01125f), Matrix4x4.Identity));
        Assert.Throws<NotSupportedException>(() => PmmOriginalSelfShadowAdapter.Create(ObservedCamera, ObservedLight,
            new(3, .01125f), Matrix4x4.Identity));
        Assert.Throws<ArgumentOutOfRangeException>(() => PmmOriginalSelfShadowAdapter.Create(ObservedCamera, ObservedLight,
            new(1, 0), Matrix4x4.Identity));
        Assert.Throws<ArgumentException>(() => PmmOriginalSelfShadowAdapter.Create(ObservedCamera with { Angle = new(float.NaN) },
            ObservedLight, new(1, .01125f), Matrix4x4.Identity));
    }

    [Fact]
    public void ParentedProjectionMatchesEquivalentGeometryAndLightInRigSpace()
    {
        var parent = Matrix4x4.CreateRotationY(.43f) * Matrix4x4.CreateRotationX(-.2f)
            * Matrix4x4.CreateTranslation(12, 8, -5);
        Assert.True(Matrix4x4.Invert(parent, out var inverse));
        var world = Matrix4x4.CreateRotationZ(.12f) * Matrix4x4.CreateTranslation(3, -2, 4);
        var pose = ObservedCamera with { ParentModelIndex = 0, ParentBoneIndex = 2 };
        var actual = PmmOriginalSelfShadowAdapter.Create(pose, ObservedLight, new(2, .023f), world,
            cameraParentTransform: parent)!;
        var q = Matrix4x4.CreateRotationY(pose.Angle.Y) * Matrix4x4.CreateRotationX(pose.Angle.X) * Matrix4x4.CreateRotationZ(pose.Angle.Z);
        var expected = OriginalShadowTransform.Create(world * inverse * q, pose.LookAt,
            Vector3.TransformNormal(Vector3.TransformNormal(ObservedLight.Direction, inverse), q), .023f, 2);
        Assert.Equal(expected.LightViewProjection, actual.LightViewProjection);
        var identityRig = PmmOriginalSelfShadowAdapter.Create(pose, ObservedLight, new(1, .01125f), world,
            cameraParentTransform: Matrix4x4.Identity);
        var identityExpected = OriginalShadowTransform.Create(world * q, pose.LookAt,
            Vector3.TransformNormal(ObservedLight.Direction, q), .01125f, 1);
        Assert.Equal(identityExpected.LightViewProjection, identityRig!.LightViewProjection);
        var ignore = PmmOriginalSelfShadowAdapter.Create(pose with { IgnoreParentRotation = true }, ObservedLight,
            new(2, .023f), world, cameraParentTransform: parent)!;
        var translated = PmmOriginalSelfShadowAdapter.Create(pose, ObservedLight, new(2, .023f), world,
            cameraParentTransform: Matrix4x4.CreateTranslation(parent.Translation))!;
        Assert.Equal(translated, ignore);
        Assert.Throws<ArgumentException>(() => PmmOriginalSelfShadowAdapter.Create(pose, ObservedLight,
            new(1, .023f), world, cameraParentTransform: Matrix4x4.CreateScale(0)));
        var scene = D3D12OriginalFrameTests.Shadow(true);
        var resolved = D3D12ViewScene.Resolve(scene, pose, ObservedLight, new(2, .023f),
            new Dictionary<Guid, CharacterMorphChannels>(), new(), pose.CreateCamera(parent), parent);
        Assert.NotNull(resolved.Options!.SelfShadow);
        Assert.Throws<NotSupportedException>(() => D3D12ViewScene.Resolve(scene, pose, ObservedLight,
            new(2, .023f), new Dictionary<Guid, CharacterMorphChannels>(), new(), SceneCamera.Default, parent));
    }

    [Fact]
    public void ViewResolvesSampledFieldsAndRejectsMissingOrInconsistentProvenance()
    {
        var scene = D3D12OriginalFrameTests.Shadow(true);
        var result = D3D12ViewScene.Resolve(scene, ObservedCamera, ObservedLight, new(2, .01125f), new Dictionary<Guid, CharacterMorphChannels>(), new(), ObservedCamera.CreateCamera());
        var expected = PmmOriginalSelfShadowAdapter.Create(ObservedCamera, ObservedLight, new(2, .01125f), scene.Surface.Snapshot.World, scene.Options!.SelfShadow);
        Assert.Equal(expected, result.Options!.SelfShadow);
        Assert.Equal(-ObservedLight.Direction, result.Surface.Snapshot.LightDirection);
        Assert.NotEqual(scene.Options.SelfShadow, result.Options.SelfShadow);
        Assert.Throws<NotSupportedException>(() => D3D12ViewScene.Resolve(scene, null, ObservedLight, new(1, .01125f), new Dictionary<Guid, CharacterMorphChannels>(), new()));
        Assert.Throws<NotSupportedException>(() => D3D12ViewScene.Resolve(scene, ObservedCamera, null, new(1, .01125f), new Dictionary<Guid, CharacterMorphChannels>(), new()));
        Assert.Throws<NotSupportedException>(() => D3D12ViewScene.Resolve(scene, ObservedCamera, ObservedLight, new(1, .01125f), new Dictionary<Guid, CharacterMorphChannels>(), new(), SceneCamera.Default));
        var disabled = D3D12ViewScene.Resolve(scene, null, null, new(0, float.NaN), new Dictionary<Guid, CharacterMorphChannels>(), new());
        Assert.Null(disabled.Options!.SelfShadow);
    }

    [Theory, Trait("Category", "Gpu")]
    [InlineData(1)]
    [InlineData(2)]
    public async Task PublicViewCaptureUsesOriginalSpaceProjection(int mode)
    {
        var initial = D3D12OriginalFrameTests.Shadow(true);
        var vertices = initial.Surface.Snapshot.Vertices.ToArray().Select(v => v with { Normal = Vector3.UnitZ }).ToArray();
        // Shadow() was authored for a right-handed camera and single-sided winding. PMM's
        // camera is left-handed; these thin receiver/caster planes are explicitly two-sided
        // so the public adapter check measures projected shadow coverage rather than culling.
        var bindings = initial.Surface.Materials.Select(m => m with { DoubleSided = true }).ToArray();
        var scene = new OriginalFrameScene(new OriginalStyleScene(initial.Surface.Snapshot.WithDeformedVertices(vertices),
            bindings, initial.Surface.Profile), options: initial.Options, materials: initial.Materials);
        var pose = new PmmCameraPose(Vector3.Zero, new(.12f, .21f, .08f), -5, 45, true);
        var light = new PmmLightPose(Vector3.One, new(.2f, -1, -1));
        var camera = pose.CreateCamera();
        var q = Matrix4x4.CreateRotationY(pose.Angle.Y) * Matrix4x4.CreateRotationX(pose.Angle.X) * Matrix4x4.CreateRotationZ(pose.Angle.Z);
        var expectedShadow = OriginalShadowTransform.Create(scene.Surface.Snapshot.World * q, new(0, 0, -5),
            Vector3.TransformNormal(light.Direction, q), .05f, mode);
        var rotation = Matrix4x4.CreateLookAtLeftHanded(camera.Eye, camera.Target, camera.Up);
        rotation.M41 = rotation.M42 = rotation.M43 = 0;
        var surface = new OriginalStyleScene(scene.Surface.Snapshot.WithLighting(-light.Direction), scene.Surface.Materials,
            scene.Surface.Profile with { LightAmbient = light.Color, LightSpecular = light.Color });
        var expected = new OriginalFrameScene(surface, scene.Outline, scene.OutlineOptions,
            new ViewQualityOptions().ApplyTo(scene.Options) with { CameraOverride = camera, SphereRotationOverride = rotation,
                SelfShadow = scene.Options!.SelfShadow! with { LightViewProjection = expectedShadow.LightViewProjection, PartialFar = mode == 2 } },
            scene.Materials, scene.Lighting, scene.EditorOverlay);
        var plan = new OfflineFramePlan(128, 96, new(30), 0, 0);
        var packet = new OfflineFrame(plan.GetSample(0), 128, 96, scene, pose, light, new((byte)mode, .05f)) { ResolvedCamera = camera };
        await using var renderer = new D3D12ViewRenderer(new(128, 96));
        using var actual = await renderer.CaptureAsync(packet, TestContext.Current.CancellationToken);
        using var reference = new D3D12FrameSession();
        var referencePixels = reference.Capture(expected, 128, 96).Rgba;
        Assert.Equal(referencePixels, actual.Pixels.ToArray());
        Assert.Contains(referencePixels.Where((_, i) => i % 4 != 3), channel => channel > 32);
        var noCaster = new OriginalFrameScene(expected.Surface, options: expected.Options,
            materials: expected.Materials.Select(m => m with { CastSelfShadow = false }));
        Assert.NotEqual(referencePixels, reference.Capture(noCaster, 128, 96).Rgba);
    }

    private static void Near(Vector4 expected, Vector4 actual, float tolerance)
    {
        Assert.InRange(MathF.Abs(expected.X - actual.X), 0, tolerance);
        Assert.InRange(MathF.Abs(expected.Y - actual.Y), 0, tolerance);
        Assert.InRange(MathF.Abs(expected.Z - actual.Z), 0, tolerance);
        Assert.InRange(MathF.Abs(expected.W - actual.W), 0, tolerance);
    }
